const EMAIL_SERVER_DOCS_URL = 'https://docs.datakitchen.io/testgen/administer/configure-email-server/';

const DESTINATION_TYPE_OPTIONS = [
    { value: 'email', label: 'Email' },
    { value: 'webhook', label: 'Webhook' },
];

const DESTINATION_TYPE_LABELS = {
    email: 'Email',
    webhook: 'Webhook',
};

const WEBHOOK_TYPE_OPTIONS = [
    { value: 'slack', label: 'Slack' },
    { value: 'microsoft_teams', label: 'Microsoft Teams' },
    { value: 'generic', label: 'Generic' },
];

const WEBHOOK_URL_HELP = {
    slack: 'The incoming webhook URL from your Slack app. Messages are posted to the channel the webhook was created for.',
    microsoft_teams: 'The URL generated by the Workflows app in Microsoft Teams, using the "When a Teams webhook request is received" trigger.',
    generic: 'The HTTPS endpoint that receives the notification.',
};

/**
 * Split raw recipient input on commas, semicolons, newlines, and spaces; drop empties.
 * De-duplicate while preserving order.
 */
const parseRecipients = (raw) => {
    if (!raw) return [];
    const seen = new Set();
    const out = [];
    for (const token of raw.split(/[,;\s]+/)) {
        const trimmed = token.trim();
        if (trimmed && !seen.has(trimmed)) {
            seen.add(trimmed);
            out.push(trimmed);
        }
    }
    return out;
};

/**
 * @typedef Destination
 * @type {object}
 * @property {string} id
 * @property {string} name
 * @property {string} destination_type
 * @property {string[]} recipients
 * @property {string} target_summary
 * @property {number} rule_count
 *
 * @typedef Properties
 * @type {object}
 * @property {VanState<Destination[]>} destinations
 * @property {VanState<boolean>} smtp_configured
 * @property {VanState<{successful: boolean, message: string, sequence: number} | null>} destination_test_result
 *
 * @param {Properties} props
 * @param {(event: string, detail?: object) => void} emit
 */
const NotificationDestinationsSection = (props, emit) => {
    const destinations = van.derive(() => getValue(props.destinations) ?? []);
    const smtpConfigured = van.derive(() => !!getValue(props.smtp_configured));
    const testResult = van.derive(() => getValue(props.destination_test_result) ?? null);
    // Shown whenever email cannot deliver, not only once an email destination exists:
    // the constraint applies while the user is deciding which type to create.
    const showSmtpWarn = van.derive(() => !smtpConfigured.val);

    const showFormDialog = van.state(false);
    const editingDestination = van.state(/** @type {Destination | null} */ (null));
    const deletingDestination = van.state(/** @type {Destination | null} */ (null));

    // The form's van.states live at section scope. If they were created inside
    // ``DestinationForm``, and that component were constructed inside a
    // reactive binding that also read ``typeState.val`` transitively (via the
    // ``emailReady`` / ``webhookReady`` / ``saveDisabled`` derives),
    // switching type would re-run the outer binding, remount the form, and
    // reset every ``van.state`` inside it. Hoisting the states out means the
    // form is constructed ONCE below and its state survives across dialog
    // opens; ``resetFormForDestination`` re-seeds them on each open.
    const formState = {
        editing: van.state(/** @type {Destination | null} */ (null)),
        name: van.state(''),
        nameValid: van.state(false),
        type: van.state('email'),
        recipientsString: van.state(''),
        recipientsValid: van.state(false),
        webhookType: van.state('slack'),
        webhookUrl: van.state(''),
        webhookUrlValid: van.state(false),
        webhookUrlPlaceholder: van.state(''),
        authHeaderName: van.state(''),
        authHeaderValue: van.state(''),
        authHeaderValueDirty: van.state(false),
        authHeaderValueSet: van.state(false),
    };

    // Bumped on every dialog open. The form binding below reads only this, so the
    // form is rebuilt once per open and never mid-edit. Rebuilding matters because
    // ``Input`` tracks whether it has been typed in with instance-local state: a
    // reused instance keeps that flag, and a freshly opened form renders the
    // "required" errors left over from the previous one.
    const formInstance = van.state(0);
    // Sequence of the newest result at the moment the dialog opened. A result at or
    // below it belongs to an earlier dialog and must not be shown as this one's.
    const testResultBaseline = van.state(0);

    const resetFormForDestination = (destination) => {
        formState.editing.val = destination;
        formState.name.val = destination?.name ?? '';
        formState.nameValid.val = !!(destination?.name ?? '');
        formState.type.val = destination?.destination_type ?? 'email';
        formState.recipientsString.val = (destination?.recipients ?? []).join(', ');
        formState.recipientsValid.val = (destination?.recipients ?? []).length > 0;
        formState.webhookType.val = destination?.webhook_type ?? 'slack';
        formState.webhookUrl.val = '';
        formState.webhookUrlValid.val = destination !== null;
        formState.webhookUrlPlaceholder.val = destination?.url_masked ?? '';
        formState.authHeaderName.val = destination?.auth_header_name ?? '';
        formState.authHeaderValue.val = '';
        formState.authHeaderValueDirty.val = false;
        formState.authHeaderValueSet.val = destination?.has_auth_header ?? false;
    };

    const openAddDialog = () => {
        editingDestination.val = null;
        resetFormForDestination(null);
        testResultBaseline.val = testResult.rawVal?.sequence ?? 0;
        formInstance.val++;
        showFormDialog.val = true;
    };
    const openEditDialog = (destination) => {
        editingDestination.val = destination;
        resetFormForDestination(destination);
        testResultBaseline.val = testResult.rawVal?.sequence ?? 0;
        formInstance.val++;
        showFormDialog.val = true;
    };
    const openDeleteDialog = (destination) => {
        deletingDestination.val = destination;
    };

    const tableRows = van.derive(() =>
        destinations.val.map((destination) => ({
            name: span(destination.name),
            destination_type: span(destination.type_summary ?? DESTINATION_TYPE_LABELS[destination.destination_type] ?? destination.destination_type),
            target_summary: span(
                { style: 'overflow: hidden; text-overflow: ellipsis; white-space: nowrap; display: block;' },
                destination.target_summary || '--',
            ),
            rule_count: span(destination.rule_count > 0 ? String(destination.rule_count) : '--'),
            actions: div(
                { class: 'flex-row', style: 'justify-content: center; gap: 4px;' },
                Button({
                    type: 'icon',
                    icon: 'edit',
                    tooltip: 'Edit destination',
                    onclick: () => openEditDialog(destination),
                }),
                Button({
                    type: 'icon',
                    icon: 'delete',
                    tooltip: 'Delete destination',
                    color: 'warn',
                    onclick: () => openDeleteDialog(destination),
                }),
            ),
        }))
    );

    return div(
        { class: 'flex-column fx-gap-2' },
        div(
            { class: 'flex-row fx-justify-space-between fx-align-flex-end' },
            span({ class: 'body m' }, 'Notification Destinations'),
            Button({
                type: 'stroked',
                icon: 'add',
                label: 'Add Destination',
                color: 'primary',
                width: 'auto',
                style: 'background: var(--button-generic-background-color);',
                onclick: openAddDialog,
            }),
        ),
        () => showSmtpWarn.val
            ? Alert(
                { type: 'warn', icon: 'warning', class: 'mb-0' },
                span('Email destinations cannot be used until an email server is configured.'),
                Link({
                    label: 'Configure an email server',
                    href: EMAIL_SERVER_DOCS_URL,
                    open_new: true,
                    right_icon: 'open_in_new',
                }),
            )
            : '',
        Table(
            {
                columns: [
                    { name: 'name', label: 'Name', width: 200, align: 'left' },
                    { name: 'destination_type', label: 'Type', width: 100, align: 'left' },
                    { name: 'target_summary', label: 'Sends To', width: 320, align: 'left', overflow: true },
                    { name: 'rule_count', label: 'Rules', width: 80, align: 'left' },
                    { name: 'actions', label: '', width: 80, align: 'center' },
                ],
                emptyState: div(
                    { class: 'flex-row fx-justify-center empty-table-message' },
                    span({ class: 'text-secondary' }, 'No notification destinations yet'),
                ),
                class: 'notification-destinations-table',
                height: 'auto',
                maxHeight: '400px',
            },
            tableRows,
            emit,
        ),
        Dialog(
            {
                title: van.derive(() => editingDestination.val ? 'Edit Destination' : 'Add Destination'),
                open: showFormDialog,
                width: '32rem',
                onClose: () => { showFormDialog.val = false; },
            },
            // Rebuilt once per dialog open, so each open gets fresh ``Input``
            // instances and none of the previous form's typed-in state. The
            // binding reads ``formInstance`` and nothing else: every other piece
            // of state the form needs is read inside its own derives, so a
            // keystroke cannot re-run this and remount the form mid-edit.
            () => {
                formInstance.val;
                return DestinationForm({
                state: formState,
                destinations,
                testResult,
                testResultBaseline,
                onCancel: () => { showFormDialog.val = false; },
                onConfirm: (payload) => {
                    showFormDialog.val = false;
                    const editing = formState.editing.rawVal;
                    if (editing) {
                        emit('EditDestinationClicked', { payload: { id: editing.id, ...payload } });
                    } else {
                        emit('AddDestinationClicked', { payload });
                    }
                },
                onSendTest: (payload) => emit('SendTestDestinationClicked', { payload }),
                });
            },
        ),
        Dialog(
            {
                title: 'Delete Destination',
                open: van.derive(() => deletingDestination.val !== null),
                width: '28rem',
                onClose: () => { deletingDestination.val = null; },
            },
            () => {
                const target = deletingDestination.val;
                if (!target) return '';
                return DeleteConfirmation({
                    destination: target,
                    onCancel: () => { deletingDestination.val = null; },
                    onConfirm: () => {
                        deletingDestination.val = null;
                        emit('DeleteDestinationClicked', { payload: { id: target.id } });
                    },
                });
            },
        ),
    );
};

/**
 * The form owns no van.state of its own -- ``state`` is created and re-seeded
 * by ``NotificationDestinationsSection`` on each dialog open. Constructing
 * derives at section scope, not inside a reactive-child binding, is what keeps
 * changing the destination type from remounting the form and wiping the
 * user's input.
 *
 * @param {{
 *   state: object,
 *   destinations: VanState<Destination[]>,
 *   onCancel: () => void,
 *   onConfirm: (payload: object) => void,
 *   onSendTest?: (payload: object) => void,
 * }} props
 */
const DestinationForm = (props) => {
    const { state, destinations, testResult, testResultBaseline, onCancel, onConfirm, onSendTest } = props;
    // A test is in flight from the click until a result newer than the baseline
    // arrives on the next rerun. Without it every click emits again, and each emit
    // carries a fresh id, so a double-click delivers twice.
    const testPending = van.state(false);
    const currentTestResult = van.derive(() => {
        const result = testResult?.val ?? null;
        if (!result || (result.sequence ?? 0) <= (testResultBaseline?.val ?? 0)) return null;
        return result;
    });
    van.derive(() => {
        if (currentTestResult.val) testPending.val = false;
    });
    const isEdit = van.derive(() => state.editing.val !== null);

    // The section provides ``destinations`` reactively so the uniqueness check
    // reflects fresh data across dialog opens.
    const existingNamesLower = van.derive(() => {
        const editingId = state.editing.val?.id;
        return destinations.val
            .filter((d) => d.id !== editingId)
            .map((d) => d.name.toLowerCase());
    });
    const nameNotUnique = van.derive(() =>
        existingNamesLower.val.includes(state.name.val.trim().toLowerCase())
    );

    const emailReady = van.derive(() =>
        state.type.val === 'email' && state.recipientsValid.val
    );
    const webhookReady = van.derive(() =>
        state.type.val === 'webhook' && state.webhookUrlValid.val
    );
    const sendTestDisabled = van.derive(() => !state.webhookUrl.val.trim() && state.editing.val === null);

    const saveDisabled = van.derive(() =>
        !state.nameValid.val
        || nameNotUnique.val
        || (state.type.val === 'email' ? !emailReady.val : !webhookReady.val)
    );

    const buildWebhookPayload = () => {
        const editing = state.editing.rawVal;
        const payload = {
            id: editing?.id ?? null,
            name: state.name.rawVal.trim(),
            destination_type: 'webhook',
            webhook_type: state.webhookType.rawVal,
            webhook_url: state.webhookUrl.rawVal.trim(),
            auth_header_name: (state.authHeaderName.rawVal || '').trim(),
        };
        // Only send ``auth_header_value`` when the user actually typed in the
        // field. Otherwise the server keeps its stored value for edits and
        // treats absence as "not set" for creates.
        if (state.authHeaderValueDirty.val) {
            payload.auth_header_value = state.authHeaderValue.rawVal.trim();
        }
        return payload;
    };

    return div(
        { class: 'flex-column fx-gap-3' },
        Input({
            label: 'Destination name',
            value: state.name,
            validators: [required],
            onChange: (value, validity) => {
                state.name.val = value;
                state.nameValid.val = validity.valid;
            },
        }),
        () => nameNotUnique.val
            ? Alert(
                { type: 'error', icon: 'error', class: 'mb-0' },
                'A destination with this name already exists.',
            )
            : '',
        Select({
            label: 'Destination type',
            value: state.type,
            options: DESTINATION_TYPE_OPTIONS,
            allowNull: false,
            // Immutable once saved: ``edit_destination`` dispatches on the
            // STORED polymorphic type, so a switched type would silently drop
            // every type-specific field while still reporting success. Delete
            // and recreate to change a destination's type.
            disabled: isEdit,
            onChange: (value) => { state.type.val = value; },
        }),
        () => state.type.val === 'email'
            ? Textarea({
                label: 'Recipients',
                value: state.recipientsString,
                help: 'List of email addresses, separated by commas or newlines',
                validators: [required, emailList],
                onChange: (value, validity) => {
                    state.recipientsString.val = value;
                    state.recipientsValid.val = validity.valid && parseRecipients(value).length > 0;
                },
            })
            : div(
                { class: 'flex-column fx-gap-3' },
                Select({
                    label: 'Webhook type',
                    value: state.webhookType,
                    options: WEBHOOK_TYPE_OPTIONS,
                    allowNull: false,
                    onChange: (value) => { state.webhookType.val = value ?? 'slack'; },
                }),
                () => Input({
                    label: 'Webhook URL',
                    value: state.webhookUrl,
                    help: WEBHOOK_URL_HELP[state.webhookType.val] ?? WEBHOOK_URL_HELP.generic,
                    placeholder: state.webhookUrlPlaceholder.val,
                    // Required on create. On edit a blank field keeps the stored URL,
                    // so only a supplied value is checked.
                    validators: [
                        requiredIf(() => state.editing.rawVal === null),
                        httpsUrl('Webhook URL'),
                    ],
                    onChange: (value, validity) => {
                        state.webhookUrl.val = value;
                        state.webhookUrlValid.val = validity.valid;
                    },
                }),
                () => state.webhookType.val === 'generic'
                    ? div(
                        { class: 'flex-column fx-gap-3' },
                        Input({
                            label: 'Authorization header name',
                            value: state.authHeaderName,
                            help: 'Sent with every request to this destination. Leave empty if the endpoint does not require authorization.',
                            onChange: (value) => { state.authHeaderName.val = value; },
                        }),
                        () => Input({
                            label: 'Authorization header value',
                            value: state.authHeaderValue,
                            placeholder: state.authHeaderValueSet.val ? '••• (stored — type to replace)' : '',
                            onChange: (value) => {
                                // ``Input`` invokes onChange once while it is being
                                // constructed, with the value the form seeded. Marking
                                // the field edited there would put an empty
                                // ``auth_header_value`` in the payload for an edit that
                                // never touched it, and the stored header would be
                                // cleared. Only a value that differs from what the form
                                // holds is a real edit -- clearing it back to empty
                                // still counts, since that is an intentional delete.
                                if (value !== state.authHeaderValue.rawVal) {
                                    state.authHeaderValueDirty.val = true;
                                }
                                state.authHeaderValue.val = value;
                            },
                        }),
                    )
                    : '',
                div(
                    { class: 'flex-row fx-justify-content-flex-end' },
                    Button({
                        type: 'stroked',
                        label: 'Send Test',
                        width: 'auto',
                        disabled: van.derive(() => sendTestDisabled.val || testPending.val),
                        onclick: () => {
                            if (!onSendTest || testPending.rawVal) return;
                            testPending.val = true;
                            onSendTest(buildWebhookPayload());
                        },
                    }),
                ),
                // Rendered inside the dialog, which stays open after a test: the
                // outcome sits next to the fields it is about and persists until the
                // next test instead of expiring on a timer.
                () => currentTestResult.val
                    ? div( // Wrapper div needed, otherwise new Alert does not appear after closing previous one
                        Alert(
                            {
                                type: currentTestResult.val.successful ? 'success' : 'error',
                                closeable: true,
                            },
                            div(
                                { class: 'flex-column fx-gap-1' },
                                span(currentTestResult.val.message),
                                currentTestResult.val.help_link
                                    ? Link({
                                        href: currentTestResult.val.help_link.href,
                                        label: currentTestResult.val.help_link.label,
                                        open_new: true,
                                        underline: true,
                                        right_icon: 'open_in_new',
                                    })
                                    : '',
                            ),
                        ),
                    )
                    : '',
            ),
        div(
            { class: 'flex-row fx-justify-content-flex-end fx-gap-2' },
            Button({
                type: 'stroked',
                label: 'Cancel',
                width: 'auto',
                onclick: onCancel,
            }),
            Button({
                type: 'flat',
                color: 'primary',
                label: van.derive(() => isEdit.val ? 'Save' : 'Add Destination'),
                width: 'auto',
                disabled: saveDisabled,
                onclick: () => {
                    if (state.type.rawVal === 'webhook') {
                        onConfirm(buildWebhookPayload());
                    } else {
                        onConfirm({
                            name: state.name.rawVal.trim(),
                            destination_type: 'email',
                            recipients: parseRecipients(state.recipientsString.rawVal),
                        });
                    }
                },
            }),
        ),
    );
};

/**
 * @param {{
 *   destination: Destination,
 *   onCancel: () => void,
 *   onConfirm: () => void,
 * }} props
 */
const DeleteConfirmation = (props) => {
    const { destination, onCancel, onConfirm } = props;
    const ruleCount = destination.rule_count ?? 0;

    return div(
        { class: 'flex-column fx-gap-3' },
        span(`Delete destination "${destination.name}"?`),
        ruleCount > 0
            ? Alert(
                { type: 'warn', icon: 'warning', class: 'mb-0' },
                ruleCount === 1
                    ? '1 notification rule uses this destination and will also be deleted.'
                    : `${ruleCount} notification rules use this destination and will also be deleted.`,
            )
            : '',
        div(
            { class: 'flex-row fx-justify-content-flex-end fx-gap-2' },
            Button({
                type: 'stroked',
                label: 'Cancel',
                width: 'auto',
                onclick: onCancel,
            }),
            Button({
                type: 'flat',
                color: 'warn',
                label: 'Delete',
                width: 'auto',
                onclick: onConfirm,
            }),
        ),
    );
};

export { NotificationDestinationsSection, parseRecipients };
